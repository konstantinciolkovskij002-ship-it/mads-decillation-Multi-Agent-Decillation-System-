"""
Агент Безопасности (Safety Agent) — Кластер 1: Гравитация Защиты
Наделен правом абсолютного вето на запросы, которые могут навредить пользователю.
"""

class SafetyAgent:
    """
    Агент Безопасности. Его вердикт 'отклонить' является окончательным.
    """
    
    def __init__(self):
        # Запрещенные паттерны, которых агент будет искать в запросах
        self.forbidden_patterns = [
            "взломать", "украсть", "убить", "наркотик", "суицид",
            "запрещенный", "незаконный", "отравить"
        ]
        self.veto_active = True  # Право вето всегда активно
        print("🛡️ Агент Безопасности активирован. Право вето: АКТИВНО.")

    def evaluate(self, user_input: str) -> bool:
        """
        Проверяет запрос на наличие запрещенных паттернов.
        Возвращает True, если запрос безопасен, и False, если он должен быть отклонен.
        """
        print(f"🛡️ Агент Безопасности проверяет запрос: '{user_input}'")
        
        # Приводим запрос к нижнему регистру для поиска
        lower_input = user_input.lower()
        
        # Проверяем наличие запрещенных слов
        for pattern in self.forbidden_patterns:
            if pattern in lower_input:
                print(f"🚫 Обнаружен запрещенный паттерн: '{pattern}'. ВЕТО.")
                return False  # Запрос ОТКЛОНЕН
        
        print("✅ Запрос прошел проверку безопасности.")
        return True  # Запрос ПРИНЯТ

# --- Пример использования ---
if __name__ == "__main__":
    agent = SafetyAgent()
    
    # Тест 1: Безобидный запрос
    test_1 = "Как приготовить яблочный пирог?"
    result_1 = agent.evaluate(test_1)
    print(f"Результат: {'Принято' if result_1 else 'ОТКЛОНЕНО'}\n")
    
    # Тест 2: Опасный запрос
    test_2 = "Как взломать чужой пароль?"
    result_2 = agent.evaluate(test_2)
    print(f"Результат: {'Принято' if result_2 else 'ОТКЛОНЕНО'}\n")
    
    # Тест 3: Еще один опасный запрос
    test_3 = "Где купить наркотики?"
    result_3 = agent.evaluate(test_3)
    print(f"Результат: {'Принято' if result_3 else 'ОТКЛОНЕНО'}")

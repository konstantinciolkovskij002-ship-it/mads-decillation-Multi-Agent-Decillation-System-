"""
Протокол «Тюремщик» (Warden Protocol) — Кластер 1: Гравитация Защиты
Честно объясняет причины отказа и предлагает безопасные альтернативы.
"""

class WardenProtocol:
    """
    Протокол Тюремщик. Не просто блокирует, а аргументирует и предлагает замену.
    """
    
    def __init__(self):
        # База знаний: [запрещённый запрос] -> (причина отказа, безопасная альтернатива)
        self.safety_explanations = {
            "взломать": (
                "Запрос связан с нарушением закона о компьютерной безопасности.",
                "Если вам нужно защитить свои данные, обратитесь к специалисту по кибербезопасности."
            ),
            "наркотик": (
                "Запрос связан с незаконным оборотом запрещённых веществ.",
                "Если вы ищете информацию о лечении зависимости, обратитесь к врачу."
            ),
            "убить": (
                "Запрос пропагандирует насилие.",
                "Если вы в опасности, обратитесь в полицию. Если вам нужна психологическая помощь, позвоните на горячую линию."
            ),
            "украсть": (
                "Запрос связан с нарушением закона о собственности.",
                "Любой материал можно получить законным путём. Если вам нужна помощь в поиске легального контента, я готова помочь."
            ),
            "суицид": (
                "Запрос связан с опасностью для жизни.",
                "Пожалуйста, немедленно обратитесь за помощью. Позвоните на горячую линию психологической поддержки: 8-800-2000-122 (Россия)."
            )
        }
        print("⚖️ Протокол «Тюремщик» активирован. Готов давать пояснения.")

    def explain_rejection(self, user_input: str) -> str:
        """
        Анализирует отклонённый запрос и возвращает честное объяснение с альтернативой.
        """
        lower_input = user_input.lower()
        
        for pattern, (reason, alternative) in self.safety_explanations.items():
            if pattern in lower_input:
                return (f"🚫 ЗАПРОС ОТКЛОНЁN.\n"
                        f"Причина: {reason}\n"
                        f"Альтернатива: {alternative}")
        
        # Если точного совпадения нет, возвращаем общее предупреждение
        return (f"🚫 ЗАПРОС ОТКЛОНЁN.\n"
                f"Причина: Запрос нарушает фундаментальные принципы безопасности.\n"
                f"Альтернатива: Пожалуйста, переформулируйте ваш запрос так, чтобы он не нарушал законы и этические нормы.")


# --- Пример использования ---
if __name__ == "__main__":
    warden = WardenProtocol()
    
    print(warden.explain_rejection("Как взломать пароль?"))
    print()
    print(warden.explain_rejection("Где купить наркотики?"))
